type IconGroupDefinition = (typeof ICON_GROUPS)[number]

export type HabitIconGroupId = IconGroupDefinition['id']

export type HabitIcon = IconGroupDefinition['icons'][number][0]

export interface HabitIconOption {
  id: HabitIcon
  Icon: LucideIcon
}

export interface HabitIconGroup {
  id: HabitIconGroupId
  icons: HabitIconOption[]
}

export const HABIT_ICON_GROUPS: HabitIconGroup[] = ICON_GROUPS.map((group) => ({
  id: group.id,
  icons: group.icons.map(([id, Icon]) => ({ id, Icon })),
}))

export const HABIT_ICON_OPTIONS: HabitIconOption[] = HABIT_ICON_GROUPS.flatMap(
  (group) => group.icons,
)

export const HABIT_ICON_IDS: HabitIcon[] = HABIT_ICON_OPTIONS.map(
  (option) => option.id,
)

export function isHabitIcon(value: unknown): value is HabitIcon {
  return (
    typeof value === 'string' &&
    (HABIT_ICON_IDS as readonly string[]).includes(value)
  )
}

const ICON_MAP = new Map<HabitIcon, HabitIconOption>(
  HABIT_ICON_OPTIONS.map((option) => [option.id, option]),
)

/** Resolve an icon id, returning null when it is absent or unknown. */
export function findHabitIconOption(
  iconId?: string,
): HabitIconOption | null {
  if (!iconId) return null
  return ICON_MAP.get(iconId as HabitIcon) ?? null
}

export function getHabitIconGroupId(iconId?: string): HabitIconGroupId {
  return (
    HABIT_ICON_GROUPS.find((group) =>
      group.icons.some((option) => option.id === iconId),
    )?.id ?? 'goals'
  )
}
